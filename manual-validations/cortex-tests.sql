SELECT * FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_REST_API_RATE_LIMIT_POLICIES;

WITH per_minute AS (
    SELECT
        MODEL_NAME,
        DATE_TRUNC('minute', START_TIME) AS minute,
        COUNT(*) AS requests,
        SUM(TOKENS) AS tokens
    FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_REST_API_USAGE_HISTORY
    WHERE START_TIME >= DATEADD('hour', -24, CURRENT_TIMESTAMP())
    GROUP BY 1, 2
)
SELECT
    p.MODEL_NAME,
    p.RPM AS limit_rpm,
    p.TPM AS limit_tpm,
    MAX(u.requests) AS peak_rpm,
    MAX(u.tokens) AS peak_tpm,
    ROUND(100 * MAX(u.requests) / NULLIF(p.RPM, 0), 2) AS rpm_usage_pct,
    ROUND(100 * MAX(u.tokens) / NULLIF(p.TPM, 0), 2) AS tpm_usage_pct
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_REST_API_RATE_LIMIT_POLICIES p
JOIN per_minute u
    ON p.MODEL_NAME = u.MODEL_NAME
GROUP BY p.MODEL_NAME, p.RPM, p.TPM
ORDER BY tpm_usage_pct DESC NULLS LAST;


