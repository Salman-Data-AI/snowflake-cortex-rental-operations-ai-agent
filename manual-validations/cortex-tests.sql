SELECT
    USAGE_TIME,
    USER_NAME,
    REQUEST_ID,
    TOKENS,
    TOKEN_CREDITS,
    TOKENS_GRANULAR
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_CODE_SNOWSIGHT_USAGE_HISTORY
WHERE USAGE_TIME >= DATEADD('hour', -6, CURRENT_TIMESTAMP())
ORDER BY USAGE_TIME DESC
LIMIT 50;


SELECT
    MAX(USAGE_TIME) AS last_recorded_usage,
    COUNT(*) AS recorded_requests,
    SUM(TOKENS) AS total_tokens,
    ROUND(SUM(TOKEN_CREDITS), 4) AS total_credits
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_CODE_SNOWSIGHT_USAGE_HISTORY
WHERE USAGE_TIME >= DATEADD('hour', -6, CURRENT_TIMESTAMP());

SELECT
    INTERFACE,
    MAX(USAGE_TIME) AS LAST_USAGE,
    COUNT(*) AS REQUESTS,
    SUM(TOKENS) AS TOTAL_TOKENS,
    ROUND(SUM(TOKEN_CREDITS), 4) AS TOTAL_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COCO_USAGE_HISTORY
GROUP BY INTERFACE
ORDER BY LAST_USAGE DESC;